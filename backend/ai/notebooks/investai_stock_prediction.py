# First, ensure there are no infinite values. StandardScaler cannot handle np.inf.
Xm_train_cleaned = np.nan_to_num(Xm_train, nan=np.nan, posinf=np.nan, neginf=np.nan)
Xm_test_cleaned  = np.nan_to_num(Xm_test, nan=np.nan, posinf=np.nan, neginf=np.nan)

# Impute NaN values. Using mean strategy from the training set.
imputer_multi = SimpleImputer(strategy='mean')
Xm_train_imputed = imputer_multi.fit_transform(Xm_train_cleaned)
Xm_test_imputed  = imputer_multi.transform(Xm_test_cleaned)

scaler_multi = StandardScaler()
Xm_train_scaled = scaler_multi.fit_transform(Xm_train_imputed)
Xm_test_scaled  = scaler_multi.transform(Xm_test_imputed)

# Training XGBoost
xgb_multi = XGBClassifier(
    n_estimators=300, max_depth=5, learning_rate=0.05,
    subsample=0.8, colsample_bytree=0.8,
    use_label_encoder=False, eval_metric='logloss',
    random_state=42, n_jobs=-1
)
xgb_multi.fit(Xm_train_scaled, ym_train, eval_set=[(Xm_test_scaled, ym_test)], verbose=False)

multi_xgb_acc = accuracy_score(ym_test, xgb_multi.predict(Xm_test_scaled))
print(f"\n🏆 Multi-Stock XGBoost Model Accuracy: {multi_xgb_acc*100:.2f}%")
print(f"   Bandingkan dengan single-stock XGBoost: {xgb_acc*100:.2f}%")

# Simpan multi-stock XGBoost model
multi_xgb_bundle = {
    'model'        : xgb_multi,
    'scaler'       : scaler_multi,
    'feature_cols' : FEATURE_COLS,
    'tickers'      : TICKERS,
    'accuracy'     : multi_xgb_acc,
    'train_date'   : str(datetime.now())
}
joblib.dump(multi_xgb_bundle, 'model_saham_multi_xgb.pkl')
print("✅ Model multi-stock XGBoost disimpan: model_saham_multi_xgb.pkl")

